import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import type { ScheduleInfo, SyncMode, SyncTrigger } from '../../shared/types';
import { timePartsInTimeZone } from '../../shared/naming';
import type { Repository } from '../db/repo';

export const LAUNCHD_LABEL = 'com.pcoprimesync.daily';

/**
 * Compute the next occurrence of the configured daily time in an IANA timezone.
 * Walking minute-by-minute through Intl keeps the result correct across DST.
 */
export function computeNextRun(
  from: Date,
  hour: number,
  minute: number,
  timezone: string,
  maxDays = 8,
): Date | null {
  const start = Math.floor(from.getTime() / 60_000) * 60_000;
  const limit = maxDays * 24 * 60;
  for (let offset = 0; offset <= limit; offset += 1) {
    const candidate = new Date(start + offset * 60_000);
    const parts = timePartsInTimeZone(candidate, timezone);
    if (parts.hour === hour && parts.minute === minute) return candidate;
  }
  return null;
}

export function launchdPlistPath(): string {
  return path.join(os.homedir(), 'Library/LaunchAgents', `${LAUNCHD_LABEL}.plist`);
}

export function isLaunchdInstalled(): boolean {
  return fs.existsSync(launchdPlistPath());
}

/** Build the launchd plist body for the daily job (documented in docs/SETUP.md). */
export function buildLaunchdPlist(options: {
  projectDir: string;
  nodePath: string;
  hour: number;
  minute: number;
  timezone: string;
}): string {
  const { projectDir, nodePath, hour, minute, timezone } = options;
  const stdout = path.join(projectDir, 'logs/sync.log');
  const stderr = path.join(projectDir, 'logs/sync.error.log');
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <!-- Generated by PCO Prime Sync. Runs the daily synchronization in ${timezone}. -->
  <key>Label</key>
  <string>${LAUNCHD_LABEL}</string>
  <key>ProgramArguments</key>
  <array>
    <string>${nodePath}</string>
    <string>--import</string>
    <string>tsx</string>
    <string>${path.join(projectDir, 'src/cli/sync.ts')}</string>
    <string>--trigger</string>
    <string>schedule</string>
  </array>
  <key>WorkingDirectory</key>
  <string>${projectDir}</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>SYNC_TIMEZONE</key>
    <string>${timezone}</string>
    <key>PATH</key>
    <string>/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin</string>
  </dict>
  <key>StartCalendarInterval</key>
  <dict>
    <key>Hour</key>
    <integer>${hour}</integer>
    <key>Minute</key>
    <integer>${minute}</integer>
  </dict>
  <key>StandardOutPath</key>
  <string>${stdout}</string>
  <key>StandardErrorPath</key>
  <string>${stderr}</string>
  <key>RunAtLoad</key>
  <false/>
</dict>
</plist>
`;
}

export interface SchedulerOptions {
  repo: Repository;
  run: (options: { mode: SyncMode; trigger: SyncTrigger }) => Promise<unknown>;
  logger?: (message: string) => void;
  /** Milliseconds between clock checks; defaults to 30s. */
  tickMs?: number;
  now?: () => Date;
}

/**
 * In-process fallback scheduler for when the dashboard is left running.
 * launchd remains the recommended mechanism (see scripts/install-launchd.mjs);
 * this class simply avoids two missed days if the Mac stayed awake.
 */
export class DailyScheduler {
  private timer: NodeJS.Timeout | null = null;
  private lastRunIsoDate: string | null = null;
  private running = false;
  private readonly options: SchedulerOptions;
  private readonly logger: (message: string) => void;

  constructor(options: SchedulerOptions) {
    this.options = options;
    this.logger = options.logger ?? ((message) => console.log(`[scheduler] ${message}`));
  }

  start(): void {
    if (this.timer) return;
    const tickMs = this.options.tickMs ?? 30_000;
    this.timer = setInterval(() => {
      void this.tick();
    }, tickMs);
    this.timer.unref?.();
    this.logger('Daily scheduler started');
  }

  stop(): void {
    if (!this.timer) return;
    clearInterval(this.timer);
    this.timer = null;
    this.logger('Daily scheduler stopped');
  }

  isRunning(): boolean {
    return this.timer !== null;
  }

  async tick(): Promise<void> {
    const settings = this.options.repo.getSettings();
    if (!settings.autoSyncEnabled) return;
    if (this.running) return;

    const now = this.options.now?.() ?? new Date();
    const parts = timePartsInTimeZone(now, settings.timezone);
    if (parts.hour !== settings.syncHour || parts.minute !== settings.syncMinute) return;
    if (this.lastRunIsoDate === parts.isoDate) return;

    this.running = true;
    this.lastRunIsoDate = parts.isoDate;
    this.logger(`Starting scheduled sync for ${parts.isoDate}`);
    try {
      await this.options.run({ mode: 'sync', trigger: 'schedule' });
    } catch (error) {
      this.logger(`Scheduled sync failed: ${error instanceof Error ? error.message : String(error)}`);
    } finally {
      this.running = false;
    }
  }
}

export function scheduleInfo(repo: Repository, now = new Date()): ScheduleInfo {
  const settings = repo.getSettings();
  const nextRun = settings.autoSyncEnabled
    ? computeNextRun(now, settings.syncHour, settings.syncMinute, settings.timezone)
    : null;
  return {
    enabled: settings.autoSyncEnabled,
    timeLabel: `${String(settings.syncHour).padStart(2, '0')}:${String(settings.syncMinute).padStart(2, '0')}`,
    timezone: settings.timezone,
    nextRunAt: nextRun ? nextRun.toISOString() : null,
    windowDays: settings.windowDays,
    launchdInstalled: isLaunchdInstalled(),
    launchdPlistPath: launchdPlistPath(),
  };
}
